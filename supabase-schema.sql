-- Communications Job Radar: private application tracking
-- Run this in Supabase SQL Editor. Uses Supabase Auth user IDs and row-level security.

create table if not exists public.job_applications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  job_id text not null,
  application_stage text not null default 'Not applied'
    check (application_stage in ('Not applied','Applied','Screening','Interview','Offer','Not moving ahead')),
  feedback_status text
    check (feedback_status is null or feedback_status in ('fit','not-fit','applied')),
  notes text not null default '',
  applied_at date,
  updated_at timestamptz not null default now(),
  unique (user_id, job_id)
);

alter table public.job_applications enable row level security;

drop policy if exists "Users can read their own applications" on public.job_applications;
create policy "Users can read their own applications"
  on public.job_applications for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Users can insert their own applications" on public.job_applications;
create policy "Users can insert their own applications"
  on public.job_applications for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update their own applications" on public.job_applications;
create policy "Users can update their own applications"
  on public.job_applications for update
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete their own applications" on public.job_applications;
create policy "Users can delete their own applications"
  on public.job_applications for delete
  to authenticated
  using ((select auth.uid()) = user_id);

create index if not exists job_applications_user_id_idx
  on public.job_applications (user_id);
create index if not exists job_applications_job_id_idx
  on public.job_applications (job_id);

-- Optional updated_at trigger
create or replace function public.set_job_application_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_job_application_updated_at on public.job_applications;
create trigger set_job_application_updated_at
before update on public.job_applications
for each row execute function public.set_job_application_updated_at();
